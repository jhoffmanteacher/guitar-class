/* The per-file audio hash map that sw.js carries (Phase 5 of the 2026-10-30
   order). One shared module so tools/checks.mjs (which writes the block into
   sw.js and fails --check when it is stale) and tools/sw-audio-proof.mjs (which
   builds test trees) cannot disagree about what a hash is or what the block
   looks like.

   sw.js keeps every audio file in ONE stable cache and remembers, per file,
   the hash of the bytes it stored (a tiny record in a second cache). At
   activate it compares each stored file's record with this map: a file the
   map no longer has, or whose hash changed, is evicted; every other file stays.
   So adding a track evicts nothing, and re-exporting one evicts that one. */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

export const AUDIO_RE = /\.(mp3|m4a|wav|ogg)$/i;
/* The block in sw.js, markers included. Never edit it by hand. */
export const AUDIO_BLOCK_RE = /\/\* AUDIO_HASHES:BEGIN[^\n]*\*\/\n[\s\S]*?\/\* AUDIO_HASHES:END \*\//;

/* First 10 hex of the file's sha256, over the raw bytes (audio is binary:
   no line-ending normalisation, unlike checks.mjs's text fingerprint). */
export function fileHash(bytes) {
  return createHash('sha256').update(bytes).digest('hex').slice(0, 10);
}

/* { 'audio/<name>': hash } for every audio file in <root>/audio, sorted. */
export function audioHashMap(root) {
  const out = {};
  let names = [];
  try { names = readdirSync(join(root, 'audio')).filter(f => AUDIO_RE.test(f)).sort(); } catch { /* no audio/ dir */ }
  for (const f of names) out[`audio/${f}`] = fileHash(readFileSync(join(root, 'audio', f)));
  return out;
}

export function renderAudioBlock(map) {
  const rows = Object.entries(map).map(([k, v]) => `  ${JSON.stringify(k)}: '${v}',`).join('\n');
  return '/* AUDIO_HASHES:BEGIN — generated by tools/checks.mjs from audio/ (path -> first 10 hex of the file\'s sha256). Never edit by hand. */\n'
    + 'const AUDIO_HASHES = {\n' + rows + '\n};\n'
    + '/* AUDIO_HASHES:END */';
}

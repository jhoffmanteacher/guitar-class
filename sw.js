const SCOPE = new URL('./', self.location.href).href;
/* The cache key and expected hash of an audio request, or null for a file this
   build has no hash for (not cached: it goes to the network as any request
   would). The key is the URL without its query, so a cache-buster cannot split
   one file into two entries. */
function audioInfo(url){
  if (!url.href.startsWith(SCOPE)) return null;
  let rel;
  try { rel = decodeURIComponent(url.pathname.slice(new URL(SCOPE).pathname.length)); } catch { return null; }
  const hash = Object.prototype.hasOwnProperty.call(AUDIO_HASHES, rel) ? AUDIO_HASHES[rel] : null;
  return hash ? { key: url.origin + url.pathname, hash } : null;
}
const AUDIO_MARKER = SCOPE + '__audio-migrated';
/* Evict what the new map no longer vouches for, and write the one-time records.
   Runs at activate and does only small reads and deletes (no file is copied or
   read), but activate holds every fetch until it finishes: measured on a Mac with
   77 tracks (the Phase 5 review), a quarter to half a second the first time (the
   migration) and about 150 ms on a later deploy. Failures are swallowed: an
   eviction that did not happen is retried at the next activate, and a cache that
   could not be opened is just an empty one. */
async function reconcileAudio(){
  const audio = await caches.open(AUDIO_CACHE), hashes = await caches.open(AUDIO_HASH_CACHE);
  const migrating = !!AUDIO_MIGRATION_FP && !(await audio.match(AUDIO_MARKER));
  for (const req of await audio.keys()) {
    if (req.url === AUDIO_MARKER) continue;   // the marker is not a track
    const info = audioInfo(new URL(req.url));
    let keep = false;
    if (info) {
      const rec = await hashes.match(req.url);
      if (rec) keep = (await rec.text()) === info.hash;
      else if (migrating) { await hashes.put(req.url, new Response(info.hash)); keep = true; }
    }
    if (!keep) { await audio.delete(req); await hashes.delete(req.url); }
  }
  for (const req of await hashes.keys()) {
    if (!(await audio.match(req.url))) await hashes.delete(req);
  }
  if (migrating) await audio.put(AUDIO_MARKER, new Response('1'));
}
/* Store a fetched file together with its record (the record last: a file with no
   record is evicted at the next activate, never trusted). */
async function storeAudio(info, res){
  const audio = await caches.open(AUDIO_CACHE), hashes = await caches.open(AUDIO_HASH_CACHE);
  await audio.put(info.key, res);
  await hashes.put(info.key, new Response(info.hash));
}

